// tools/dbm1/gen-pg-schema.js
// DB-M1 — ONE-OFF generator. Introspects the authoritative A3 SQLite schema
// (as built by database/init-db.js) and emits the PostgreSQL baseline migration.
// The EMITTED .sql files are the authoritative PostgreSQL schema and are
// reviewed + committed; this tool only documents how they were derived.
// It needs the legacy SQLite initDb, so it runs against docs/legacy-sqlite/.
const fs = require('fs');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');

const LEGACY_INIT = process.argv[2];             // path to legacy init-db.js
const OUT = process.argv[3];                     // output dir
const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
require(path.resolve(LEGACY_INIT)).initDb(db);

// ---- deliberate type mapping -------------------------------------------------
const TS_RE = /(_at$|timestamp$)/i;
const DATE_COLS = new Set(`as_of_date assignment_effective_from birth_date clock_out_date contract_end
contract_start cycle_start_date date effective_date effective_from effective_to end_date expiry_date
jkk_rate_effective_from payment_date payroll_group_effective_from payroll_rule_set_effective_from
period_end period_start permanent_date service_date service_period_end service_period_start start_date
termination_date work_calendar_effective_from work_date attendance_cutoff overtime_cutoff
adjustment_cutoff`.split(/\s+/));
function pgType(table, col) {
  if (col.type === 'INTEGER') return 'BIGINT';          // SQLite INTEGER is 64-bit: only lossless map
  if (col.type === 'REAL') return 'DOUBLE PRECISION';   // legacy display hours; minutes are authoritative
  if (TS_RE.test(col.name) || /datetime\('now'\)/.test(col.dflt_value || '')) return 'TIMESTAMPTZ';
  if (DATE_COLS.has(col.name)) return 'DATE';
  return 'TEXT';
}

// ---- helpers -----------------------------------------------------------------
const stripComments = (s) => s.replace(/--[^\n]*/g, '');
function splitTop(body) {
  const out = []; let depth = 0; let cur = ''; let q = null;
  for (const ch of body) {
    if (q) { cur += ch; if (ch === q) q = null; continue; }
    if (ch === "'" ) { q = ch; cur += ch; continue; }
    if (ch === '(') depth++; if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}
const fixExpr = (e) => e.replace(/datetime\('now'\)/gi, 'kahe_now()')
  .replace(/\bIFNULL\(/gi, 'COALESCE(').replace(/\s+IS NOT\s+(?!NULL)/gi, ' IS DISTINCT FROM ')
  .replace(/\s+/g, ' ').trim();

const tables = db.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").all();
const colTypes = {};
const tableDDL = {}; const deps = {};
for (const t of tables) {
  const info = db.prepare(`PRAGMA table_info(${t.name})`).all();
  colTypes[t.name] = Object.fromEntries(info.map((c) => [c.name, pgType(t.name, c)]));
  const sql = stripComments(t.sql);
  const body = sql.slice(sql.indexOf('(') + 1, sql.lastIndexOf(')'));
  const items = splitTop(body);
  // ALTER TABLE ADD COLUMN appends raw text to the stored sql; table_info is
  // authoritative for the column list, the text for constraints.
  const colNames = new Set(info.map((c) => c.name));
  const lines = []; deps[t.name] = new Set();
  for (const item of items) {
    const first = item.split(/\s+/)[0].replace(/"/g, '');
    if (colNames.has(first) && !/^(PRIMARY|UNIQUE|CHECK|FOREIGN|CONSTRAINT)$/i.test(first)) {
      const c = info.find((x) => x.name === first);
      let rest = item.slice(item.indexOf(first) + first.length).trim()
        .replace(/^(INTEGER|TEXT|REAL)\b/i, '').trim();
      let type = colTypes[t.name][first];
      if (/PRIMARY KEY\s+AUTOINCREMENT/i.test(rest)) {
        rest = rest.replace(/PRIMARY KEY\s+AUTOINCREMENT/i, 'GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
      }
      rest = rest.replace(/DEFAULT\s+\(datetime\('now'\)\)/i, 'DEFAULT kahe_now()');
      rest = fixExpr(rest);
      const q = first === 'date' ? '"date"' : first;
      lines.push(`  ${q} ${type}${rest ? ' ' + rest : ''}`);
      for (const m of rest.matchAll(/REFERENCES\s+(\w+)/gi)) if (m[1] !== t.name) deps[t.name].add(m[1]);
    } else {
      lines.push('  ' + fixExpr(item));
      for (const m of item.matchAll(/REFERENCES\s+(\w+)/gi)) if (m[1] !== t.name) deps[t.name].add(m[1]);
    }
  }
  tableDDL[t.name] = `CREATE TABLE ${t.name} (\n${lines.join(',\n')}\n);`;
}
// dependency-safe order (topological, from ACTUAL foreign keys)
const order = []; const seen = new Set();
const visit = (n, stack = []) => {
  if (seen.has(n)) return; if (stack.includes(n)) throw new Error('FK cycle: ' + [...stack, n].join('>'));
  for (const d of deps[n]) if (tableDDL[d]) visit(d, [...stack, n]);
  seen.add(n); order.push(n);
};
for (const t of tables) visit(t.name);

// ---- indexes -----------------------------------------------------------------
const indexes = db.prepare("SELECT name, tbl_name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY rowid").all()
  .map((i) => fixExpr(stripComments(i.sql)).replace(/\bIF NOT EXISTS\s+/i, '').replace(/\(date\b/g, '("date"').replace(/, date\b/g, ', "date"') + ';');

// ---- triggers ----------------------------------------------------------------
const trig = db.prepare("SELECT name, tbl_name, sql FROM sqlite_master WHERE type='trigger' ORDER BY rowid").all().map((t) => {
  const s = stripComments(t.sql).replace(/\s+/g, ' ');
  const m = s.match(/CREATE TRIGGER (?:IF NOT EXISTS )?(\w+) BEFORE (INSERT|UPDATE|DELETE)(?: OF ([\w, ]+))? ON (\w+)(?: WHEN (.*?))? BEGIN SELECT RAISE\(ABORT, '((?:[^']|'')*)'\); END/i);
  if (!m) throw new Error('unparsed trigger ' + t.name);
  const [, name, op, ofCols, table, when, msg] = m;
  const cond = when ? fixExpr(when) : null;
  const ret = op === 'DELETE' ? 'OLD' : 'NEW';
  return `CREATE FUNCTION ${name}_fn() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
${cond ? `  IF (${cond}) THEN\n    RAISE EXCEPTION '${msg}' USING ERRCODE = 'KH001';\n  END IF;` : `  RAISE EXCEPTION '${msg}' USING ERRCODE = 'KH001';`}
  RETURN ${ret};
END
$fn$;
CREATE TRIGGER ${name} BEFORE ${op}${ofCols ? ' OF ' + ofCols.trim() : ''} ON ${table}
  FOR EACH ROW EXECUTE FUNCTION ${name}_fn();`;
});

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'tables.sql'), order.map((n) => tableDDL[n]).join('\n\n') + '\n');
fs.writeFileSync(path.join(OUT, 'indexes.sql'), indexes.join('\n') + '\n');
fs.writeFileSync(path.join(OUT, 'triggers.sql'), trig.join('\n\n') + '\n');
fs.writeFileSync(path.join(OUT, 'meta.json'), JSON.stringify({ order, colTypes }, null, 1));
console.log(`tables ${order.length}, indexes ${indexes.length}, triggers ${trig.length}`);
